package com.itheima.operator;

public class OperatorDemo3 {
    public static void main(String[] args) {
        //实现大小写字母的转换
        char c = 'A';

        char cc = (char) (c + 32);
        System.out.println(cc);

        //字符串拼接：任意数据 + 字符串
        System.out.println(10 + 8 + "岁" + 1 + 2);

    /*
    赋值运算符
      =
      +=
      -=
      /=
      %=
      *=
    */
    }
}
